'use strict';

/**
 * Engine scaffold generator.
 *
 * Produces one contract-complete engine file per provider.
 *
 * These are scaffolds, not working engines. The endpoint paths and request shapes for a
 * provider's private web API cannot be written blind - they have to be observed in a
 * real browser session. A scaffold that guessed an endpoint and appeared to work would
 * be worse than no scaffold, because a wrong path fails at runtime with a confusing
 * 404 and a plausible-looking implementation invites exactly that.
 *
 * So every generated engine ships `verified: false` and REFUSES to issue a request
 * until an operator has observed the real endpoint and flipped the flag. The contract
 * surface, the auth requirements, the failure classification and the state handling are
 * all real and done; only the wire details are left blank, and they are left visibly
 * blank rather than filled with a guess.
 *
 * Usage:  node scripts/make-engine-scaffold.cjs
 * Existing files are never overwritten.
 */

